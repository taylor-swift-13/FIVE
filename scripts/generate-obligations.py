"""Generate unproved safety/termination propositions for a CompCert C function.

Requires an already exported Csyntax program. By default, leave the
precondition and proofs for later authoring in separate files.
Does not infer a precondition, execute the model, or prove either property.
"""
import argparse
from pathlib import Path
import re


def import_line(module):
    if "." in module:
        prefix, name = module.rsplit(".", 1)
        return f"From {prefix} Require Import {name}."
    return f"Require Import {module}."


def qualified_name(value):
    if not re.fullmatch(r"[A-Za-z_][A-Za-z_0-9]*(\.[A-Za-z_][A-Za-z_0-9]*)*", value):
        raise argparse.ArgumentTypeError("Expected a Rocq qualified identifier")
    return value


def render(source_module, program, function, precondition_module, precondition):
    return f"""(* Generated by scripts/generate-obligations.py.  All targets are UNPROVED.
   Keep proofs in another module; regenerating this file never proves a goal. *)
From Stdlib Require Import List.
From compcert Require Import Values Memory Ctypes Csem.
From FiveShared.verification Require Import Obligations.
{import_line(source_module)}
{import_line(precondition_module)}

Definition goal_ge : Csem.genv := Csem.globalenv {source_module}.{program}.
Definition goal_entry (args : list val) (m : mem) : Csem.state :=
  Callstate (Ctypes.Internal {source_module}.{function}) args Kstop m.

(* The execution entry is unrestricted.  Only the following proof obligations
   use the explicitly selected precondition. *)
Definition goal_precondition : list val -> mem -> Prop :=
  {precondition_module}.{precondition}.

Definition no_error_goal : Prop :=
  forall args m, goal_precondition args m ->
    FiveShared.verification.Obligations.no_error goal_ge (goal_entry args m).

Definition termination_goal : Prop :=
  forall args m, goal_precondition args m ->
    FiveShared.verification.Obligations.terminates goal_ge (goal_entry args m).

(* Typecheck the pending goals without admitting or exporting a theorem. *)
Goal no_error_goal.
Abort.
Goal termination_goal.
Abort.
"""


def pending_templates(source_module, program, function, precondition_module,
                      goal_name="Obligations"):
    prefix = precondition_module.rsplit(".", 1)[0]
    return {
        "Precondition.v": """From Stdlib Require Import List.
From compcert Require Import Values Memory.

(* PENDING: the LLM must supply the actual precondition later.
   This type is an interface, not an assumed or inferred input restriction.
   Retain this declaration and add a Definition precondition of this type.
   List calling-convention, memory, numeric and environment requirements here;
   justify their scope and satisfiability. Do not fill with a dummy True/False. *)
Definition precondition_type : Type := list val -> mem -> Prop.

(* No concrete precondition has been supplied. *)
""",
        goal_name + ".v": f"""(* Generated targets only: precondition pending; both proofs pending.
   All possible original CompCert Csem steps are covered, without a fuel bound. *)
From Stdlib Require Import List.
From compcert Require Import Values Memory Ctypes Csem.
From FiveShared.verification Require Import Obligations.
{import_line(source_module)}
{import_line(precondition_module)}

Definition goal_ge : Csem.genv := Csem.globalenv {source_module}.{program}.
Definition goal_entry (args : list val) (m : mem) : Csem.state :=
  Callstate (Ctypes.Internal {source_module}.{function}) args Kstop m.

(* [pre] is a bound parameter, not a global axiom or a chosen input domain. *)
Definition no_error_goal (pre : {precondition_module}.precondition_type) : Prop :=
  forall args m, pre args m ->
    FiveShared.verification.Obligations.no_error goal_ge (goal_entry args m).

Definition termination_goal (pre : {precondition_module}.precondition_type) : Prop :=
  forall args m, pre args m ->
    FiveShared.verification.Obligations.terminates goal_ge (goal_entry args m).
""",
        "Proofs.v": f"""{import_line(prefix + '.' + goal_name)}
{import_line(precondition_module)}

(* PENDING: no program theorem is exported from this file.
   After the LLM defines [Precondition.precondition], it can replace this
   comment with proofs of the following statements:

Theorem no_error : no_error_goal Precondition.precondition.
Proof.
  (* Supply a proof over original Csem here. *)
Qed.

Theorem termination : termination_goal Precondition.precondition.
Proof.
  (* Supply a proof for every possible successor, e.g. by a ranking argument. *)
Qed.

   Do not use Admitted or an Axiom to complete a pending target.
*)
""",
    }


def write_pending(output, source_module, program, function, precondition_module):
    if output.suffix != ".v" or not re.fullmatch(r"[A-Za-z_][A-Za-z_0-9]*", output.stem):
        raise ValueError("Output must be a .v file with a Rocq module identifier")
    if not precondition_module.endswith(".Precondition"):
        raise ValueError("Pending mode requires a qualified module ending in .Precondition")
    if output.stem in {"Precondition", "Proofs"}:
        raise ValueError("The goal file must be distinct from Precondition.v and Proofs.v")
    templates = pending_templates(source_module, program, function,
                                  precondition_module, output.stem)
    # The generated target must stay deterministic. Human-authored files are
    # initialized only when absent, so re-export never destroys later work.
    if output.exists() and output.read_text(encoding="utf-8") != templates[output.name]:
        raise ValueError("Generated target differs; choose a new output path")
    output.parent.mkdir(parents=True, exist_ok=True)
    for name, content in templates.items():
        path = output.parent / name
        if path == output or not path.exists():
            path.write_text(content, encoding="utf-8")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source-module", type=qualified_name, required=True)
    parser.add_argument("--program", type=qualified_name, default="prog")
    parser.add_argument("--function", type=qualified_name, required=True)
    parser.add_argument("--precondition-module", type=qualified_name, required=True)
    parser.add_argument("--precondition", type=qualified_name,
                        help="Use an existing predicate; omit to leave it pending")
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    if args.precondition is None:
        try:
            write_pending(args.output, args.source_module, args.program,
                          args.function, args.precondition_module)
        except ValueError as error:
            parser.error(str(error))
        print(f"Generated {args.output}: 2 UNPROVED parameterized goals; "
              "Precondition.v and Proofs.v initialized only if absent; "
              "no precondition inferred or proof attempted")
        return
    content = render(args.source_module, args.program, args.function,
                     args.precondition_module, args.precondition)
    # Refuse to overwrite a different existing file, which could contain work.
    if args.output.exists() and args.output.read_text(encoding="utf-8") != content:
        parser.error("Output differs; choose a new path or explicitly remove the old generated file")
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(content, encoding="utf-8")
    print(f"Generated {args.output}: 2 UNPROVED goals; no execution or proof attempted")


if __name__ == "__main__":
    main()
